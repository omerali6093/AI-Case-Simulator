// Regenerates frontend/js/demo-data.js (used only by the offline demo) from the seed data,
// so the demo and the server always teach the same cases.   node scripts/sync-demo-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const cases = JSON.parse(readFileSync(new URL('../src/seed/cases.data.json', import.meta.url), 'utf8'));
const out = `/* Generated by backend/scripts/sync-demo-data.mjs from backend/src/seed/cases.data.json. Used only by the offline demo. */\nwindow.CLINIC_DEMO_CASES = ${JSON.stringify(cases, null, 1)};\n`;
writeFileSync(new URL('../../frontend/js/demo-data.js', import.meta.url), out);
console.log(`Wrote ${cases.length} cases to frontend/js/demo-data.js`);
